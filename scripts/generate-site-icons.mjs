import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { JSDOM } from "jsdom";
import * as lucide from "lucide-react";

const names = new Set();
function scan(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) scan(path);
    else if (entry.name.endsWith(".tsx") && entry.name !== "icons.tsx") {
      const text = readFileSync(path, "utf8");
      for (const match of text.matchAll(/import\s*\{([^}]+)\}\s*from "(?:lucide-react|@\/components\/site\/icons)"/g)) {
        for (const name of match[1].split(",").map((name) => name.trim())) {
          if (name && !name.startsWith("type ")) names.add(name);
        }
      }
    }
  }
}
scan("src");
const attributeName = (name) => /^(aria-|data-)/.test(name) ? name : name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
function jsx(element) {
  const attrs = [...element.attributes].map((attr) => `${attributeName(attr.name)}={${JSON.stringify(attr.value)}}`).join(" ");
  return `<${element.localName} ${attrs}>${[...element.children].map(jsx).join("")}</${element.localName}>`;
}
const license = readFileSync("node_modules/lucide-react/LICENSE", "utf8").trim();
let output = `/*!\n${license}\n*/\n// Generated by scripts/generate-site-icons.mjs; do not edit by hand.\nimport type { ComponentType, ReactNode, SVGProps } from "react";\n\nexport type IconProps = SVGProps<SVGSVGElement> & { size?: number | string };\nexport type LucideIcon = ComponentType<IconProps>;\n\nfunction icon(baseClass: string, nodes: ReactNode): LucideIcon {\n  return function SiteIcon({ size = 24, color = "currentColor", className, children, ...props }: IconProps) {\n    const named = Object.keys(props).some((key) => key.startsWith("aria-") || key === "role" || key === "title");\n    return <svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 24 24" fill="none" stroke={color} strokeWidth={2} strokeLinecap="round" strokeLinejoin="round" className={className ? baseClass + " " + className : baseClass} aria-hidden={named ? undefined : true} {...props}>{nodes}{children}</svg>;\n  };\n}\n\n`;
for (const name of [...names].sort()) {
  if (!lucide[name]) throw new Error(`Unknown icon ${name}`);
  const markup = renderToStaticMarkup(createElement(lucide[name]));
  const dom = new JSDOM(markup, { contentType: "image/svg+xml" });
  const svg = dom.window.document.documentElement;
  output += `export const ${name} = /*#__PURE__*/ icon(${JSON.stringify(svg.getAttribute("class"))}, <>${[...svg.children].map(jsx).join("")}</>);\n`;
  dom.window.close();
}
const file = "src/components/site/icons.tsx";
if (process.argv.includes("--check")) {
  if (readFileSync(file, "utf8") !== output) throw new Error("Inline icons are stale; run npm run prebuild");
} else writeFileSync(file, output);
